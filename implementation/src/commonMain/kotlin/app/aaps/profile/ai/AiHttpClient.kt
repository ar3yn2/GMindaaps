@Serializable
data class AiApiRequest(
    val prompt: String,
    val analysisData: String,
    val configVersion: String = "1.0"
)

@Serializable
data class AiApiResponse(
    @SerialName("isf_shift_percent")
    val isfShiftPercent: Double? = null,

    @SerialName("basal_shift_percent")
    val basalShiftPercent: Double? = null,

    @SerialName("target_bg_shift")
    val targetBgShift: Int? = null,

    val confidence: Float? = null,
    val reason: String? = null,

    @SerialName("projected_a1c_change")
    val projectedA1cChange: Double? = null,

    @SerialName("contributing_factors")
    val contributingFactors: List<String>? = null
)

