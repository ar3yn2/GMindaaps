    private val httpClient = HttpClient(OkHttp) {
        install(HttpTimeout) {
            connectTimeoutMillis = CONNECT_TIMEOUT_MS
            requestTimeoutMillis = DEFAULT_TIMEOUT_MS
            socketTimeoutMillis = DEFAULT_TIMEOUT_MS
        }
        
        install(ContentNegotiation) {
            json(jsonConfig)
        }

        expectSuccess = false
    }

    override suspend fun sendAnalysisRequest(
        config: AiProfileConfig,
        analysisResult: AnalysisResult
    ): ProfileRecommendation? {
        return withContext(Dispatchers.IO) {
            val apiUrl = configStore.getApiUrl()
            val apiKey = configStore.getApiKey()

            if (apiUrl.isBlank() || apiKey.isBlank()) {
                logger("AI: API URL or key is empty")
                return@withContext null
            }

            try {
                val prompt = buildAiPrompt(analysisResult, config)
                
                val payload = AiApiRequest(
                    prompt = prompt,
                    analysisData = analysisResult.toJsonPayload(),
                    configVersion = "1.0"
                )

                val response = httpClient.post(apiUrl) {
                    contentType(ContentType.Application.Json)
                    setBody(payload)
                    header("Authorization", "Bearer $apiKey")
                    header("X-Client-Version", "1.0")
                    header("X-Platform", "AndroidAPS-KotlinMultiplatform")
                }

                if (response.status.value !in 200..299) {
                    logger("AI: API returned ${response.status.value}")
                    return@withContext null
                }

                val aiResponse = response.body<AiApiResponse>()
                parseAiResponse(aiResponse, config)
                
            } catch (e: Exception) {
                logger("AI: Request failed: ${e.message}")
                null
            }
        }
    }

    private fun parseAiResponse(response: AiApiResponse, config: AiProfileConfig): ProfileRecommendation? {
        return try {
            val isfShift = response.isfShiftPercent?.coerceIn(
                -config.aggressiveness.maxIsfShiftPercent(),
                config.aggressiveness.maxIsfShiftPercent()
            ) ?: 0.0

            val basalShift = response.basalShiftPercent?.coerceIn(
                -config.aggressiveness.maxBasalShiftPercent(),
                config.aggressiveness.maxBasalShiftPercent()
            ) ?: 0.0

            val confidence = (response.confidence ?: 0.5f).coerceIn(0f, 1f)

            if (isfShift == 0.0 && basalShift == 0.0) {
                return ProfileRecommendation.noChange(response.reason ?: "Profile is optimal")
            }

            ProfileRecommendation(
                isfShiftPercent = isfShift.toFloat(),
                basalShiftPercent = basalShift.toFloat(),
                targetBgShift = response.targetBgShift,
                confidence = confidence,
                reason = response.reason ?: "AI recommended change",
                projectedA1cChange = response.projectedA1cChange,
                contributingFactors = response.contributingFactors.orEmpty()
            )
        } catch (e: Exception) {
            logger("AI: Failed to parse response: ${e.message}")
            null
        }
    }

    override suspend fun testConnection(config: AiProfileConfig): TestResult {
        return withContext(Dispatchers.IO) {
            val apiUrl = config.apiUrl
            val apiKey = config.apiKey
            
            if (apiUrl.isBlank() || apiKey.isBlank()) {
                return@withContext TestResult.Success(false, "API URL or key is empty")
            }

            try {
                val startTime = System.currentTimeMillis()
                
                val response = httpClient.post(apiUrl) {
                    contentType(ContentType.Application.Json)
                    setBody(AiApiRequest(
                        prompt = "Test: return isfShiftPercent=0.05, basalShiftPercent=-0.03",
                        analysisData = "{\"test\":true}",
                        configVersion = "1.0"
                    ))
                    header("Authorization", "Bearer $apiKey")
                }

                val elapsed = System.currentTimeMillis() - startTime

                if (response.status.value in 200..299) {
                    TestResult.Success(true, "Connection established in ${elapsed}ms")
                } else {
                    TestResult.Success(false, "HTTP error: ${response.status.value}, elapsed: ${elapsed}ms")
                }

            } catch (e: Exception) {
                TestResult.Success(false, "Error: ${e.message}")
            }
        }
    }

    fun close() {
        httpClient.close()
    }
}

